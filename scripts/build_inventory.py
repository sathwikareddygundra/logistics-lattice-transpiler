"""Per-plant schema inventory (T-9): tables, columns, types, row counts, sample rows and the
known gaps between plants. Writes schemas/inventory/<PLANT>.json and docs/known-gaps.md.

Usage: PYTHONPATH=. uv run python scripts/build_inventory.py
"""

import json
import sqlite3
import tempfile
from pathlib import Path

import duckdb

from plantdb.plants import Plant, build_plant_databases, get_profile

ROOT = Path(__file__).resolve().parent.parent
GAPS = [
    "Dispatch_Date is stored in both dispatch and turnaround_time in the source CSVs; the "
    "canonical model owns it once (on dispatch).",
    "tracking.last_known_location mixes hub codes (Hub_323) and city names in one column.",
    "turnaround_time.total_tat_hours takes only about 22 distinct values: bucketed, not raw.",
    "There are no dimension tables for drivers, warehouses or carriers.",
    "Plants use different physical table names (dispatch vs ycw_dispatch vs vgu_dispatch); "
    "ir/adapters.py normalizes this once, at IR level.",
    "Plants run different engines (SQLite, DuckDB, PostgreSQL-capable); timestamps are TEXT in "
    "SQLite but TIMESTAMP in DuckDB and PostgreSQL. Dialect handling: docs/dialects.md.",
    "Each plant holds a disjoint third of the invoices (invoice sequence number mod 3), so "
    "plant-level totals only make sense summed across plants.",
]


def _count(conn, name: str) -> int:
    row = conn.execute(f"SELECT COUNT(*) FROM {name}").fetchone()
    assert row is not None
    return int(row[0])


def _sqlite(path: Path) -> dict:
    conn = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    out = {}
    for (name,) in conn.execute("SELECT name FROM sqlite_master WHERE type='table' ORDER BY name"):
        cols = conn.execute(f"PRAGMA table_info('{name}')").fetchall()
        out[name] = {
            "columns": [{"name": c[1], "type": c[2]} for c in cols],
            "rows": _count(conn, name),
            "sample": [list(map(str, r)) for r in conn.execute(f"SELECT * FROM {name} LIMIT 3")],
        }
    conn.close()
    return out


def _duckdb(path: Path) -> dict:
    conn = duckdb.connect(str(path), read_only=True)
    out = {}
    for (name,) in conn.execute(
        "SELECT table_name FROM information_schema.tables ORDER BY 1"
    ).fetchall():
        cols = conn.execute(
            "SELECT column_name, data_type FROM information_schema.columns "
            "WHERE table_name = ? ORDER BY ordinal_position", [name],
        ).fetchall()  # fmt: skip
        out[name] = {
            "columns": [{"name": c, "type": t} for c, t in cols],
            "rows": _count(conn, name),
            "sample": [
                list(map(str, r)) for r in conn.execute(f"SELECT * FROM {name} LIMIT 3").fetchall()
            ],
        }
    conn.close()
    return out


def build() -> dict[str, dict]:
    dbs = build_plant_databases(tempfile.mkdtemp())
    inv: dict[str, dict] = {}
    for plant in Plant:
        profile = get_profile(plant)
        tables = (
            _duckdb(Path(dbs[plant])) if profile.engine == "duckdb" else _sqlite(Path(dbs[plant]))
        )
        inv[plant.value] = {
            "plant": plant.value,
            "engine": profile.engine,
            "dialect": profile.dialect,
            "tables": tables,
            "known_gaps": GAPS,
        }
    return inv


if __name__ == "__main__":
    inv = build()
    out = ROOT / "schemas" / "inventory"
    out.mkdir(exist_ok=True)
    for plant, doc in inv.items():
        (out / f"{plant}.json").write_text(json.dumps(doc, indent=1, sort_keys=True) + "\n")
    lines = [
        "# Known gaps across plants (T-9)",
        "",
        "Generated by `scripts/build_inventory.py`.",
        "",
    ]
    lines += [f"{i}. {g}" for i, g in enumerate(GAPS, 1)]
    lines += [
        "",
        "## Per-plant overview",
        "",
        "| Plant | Engine | Tables | Rows (dispatch) |",
        "|---|---|---|---|",
    ]
    for plant, doc in inv.items():
        disp = next(v for k, v in doc["tables"].items() if "dispatch" in k)
        lines.append(f"| {plant} | {doc['engine']} | {', '.join(doc['tables'])} | {disp['rows']} |")
    (ROOT / "docs" / "known-gaps.md").write_text("\n".join(lines) + "\n")
    print("inventory written:", {p: list(d["tables"]) for p, d in inv.items()})
